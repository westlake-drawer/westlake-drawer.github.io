import {existsSync, readdirSync, readFileSync} from 'node:fs';
import path from 'node:path';
import {contentRoot} from './content-source.mjs';

const defaultDocsRoot = path.join(contentRoot, 'docs');
const collator = new Intl.Collator('en', {sensitivity: 'base'});
const directoryLabel = (name) => name.replaceAll('-', ' ').replace(/\b[a-z]/g, (letter) => letter.toUpperCase());

export function discoverDocSections(docsRoot = defaultDocsRoot) {
  return readdirSync(docsRoot, {withFileTypes: true})
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith('_') && !entry.name.startsWith('.'))
    .filter(({name}) => ['index.md', 'index.mdx'].some((file) => existsSync(path.join(docsRoot, name, file))))
    .map(({name}) => {
      const filename = path.join(docsRoot, name, '_category_.json');
      const metadata = existsSync(filename) ? JSON.parse(readFileSync(filename, 'utf8')) : {};
      if (metadata.label !== undefined && (typeof metadata.label !== 'string' || !metadata.label.trim())) {
        throw new Error(`Invalid category label: ${filename}`);
      }
      return {directory: name, sidebarId: `${name}Sidebar`, label: metadata.label ?? directoryLabel(name)};
    })
    .sort((a, b) => collator.compare(a.label, b.label) || collator.compare(a.directory, b.directory));
}

const exploreNote = {
  type: 'html',
  value: '收录课程笔记与学习工具；不收录题集与往年试题，也不以应试为目标。',
  className: 'sidebar-scope-note',
};

export function sectionSidebars(sections) {
  return Object.fromEntries(sections.map(({directory, sidebarId}) => {
    const autogenerated = {type: 'autogenerated', dirName: directory};
    return [sidebarId, directory === 'explore' ? [exploreNote, autogenerated] : [autogenerated]];
  }));
}

export function sectionNavbarItems(sections) {
  return sections.map(({sidebarId, label}) => ({type: 'docSidebar', sidebarId, position: 'left', label}));
}

export function withGeneratedCategoryLinks(args) {
  const root = args.item.dirName;
  const inRoot = (directory) => root === '.' || directory === root || directory.startsWith(`${root}/`);
  const docs = args.docs.filter((doc) => inRoot(doc.sourceDirName));
  const indexes = new Set(docs.filter((doc) => {
    const {name: fileName, ext: extension} = path.posix.parse(doc.source);
    return args.isCategoryIndex({
      fileName, extension, directories: doc.sourceDirName.split('/').reverse(),
    });
  }).map((doc) => doc.sourceDirName));
  const categoriesMetadata = {...args.categoriesMetadata};
  const directories = new Set();
  for (const doc of docs) {
    let directory = doc.sourceDirName;
    while (directory !== root && directory !== '.' && inRoot(directory)) {
      directories.add(directory);
      directory = path.posix.dirname(directory);
    }
  }
  for (const directory of directories) {
    const metadata = categoriesMetadata[directory] ?? {};
    const label = metadata.label ?? directoryLabel(path.posix.basename(directory));
    categoriesMetadata[directory] = {
      ...metadata,
      // Native index documents and explicit links keep their published routes.
      ...(!indexes.has(directory) && metadata.link === undefined && {
        label,
        link: {
          type: 'generated-index', slug: `/${directory}`, title: label,
          ...(metadata.description && {description: metadata.description}),
        },
      }),
    };
  }
  return {...args, categoriesMetadata};
}
