import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, mkdir, writeFile, rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {discoverDocSections, sectionSidebars, sectionNavbarItems, withGeneratedCategoryLinks} from '../lib/docs-navigation.mjs';
import createStarSortedSidebarGenerator from '../plugins/sidebar-stars.mjs';

test('a new root section automatically supplies its sidebar and navbar entry', async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'docs-sections-'));
  try {
    for (const name of ['tools', 'research', 'empty', '_draft', '.hidden']) {
      await mkdir(path.join(root, name));
      if (name !== 'empty') await writeFile(path.join(root, name, 'index.mdx'), '# Root');
    }
    await writeFile(path.join(root, 'research/_category_.json'), '{"label":"Research Library"}');
    const sections = discoverDocSections(root);
    assert.deepEqual(sections.map(({label}) => label), ['Research Library', 'Tools']);
    assert.deepEqual(sectionSidebars(sections), {
      researchSidebar: [{type: 'autogenerated', dirName: 'research'}],
      toolsSidebar: [{type: 'autogenerated', dirName: 'tools'}],
    });
    assert.deepEqual(sectionNavbarItems(sections)[0],
      {type: 'docSidebar', sidebarId: 'researchSidebar', position: 'left', label: 'Research Library'});
  } finally {
    await rm(root, {recursive: true, force: true});
  }
});

const doc = (directory, name = 'article.md') =>
  ({sourceDirName: directory, source: `@site/docs/${directory}/${name}`});
const isCategoryIndex = ({fileName}) => fileName === 'index';

test('all nested directories get native generated pages unless they have authored index content or explicit links', () => {
  const args = {
    item: {dirName: 'research'}, isCategoryIndex,
    docs: [doc('research'), doc('research/ai-tools/plugins/deep'), doc('research/custom', 'index.md'),
      doc('research/legacy'), doc('tools/excluded')],
    categoriesMetadata: {
      'research/ai-tools': {label: 'AI Tools', description: 'AI integrations'},
      'research/legacy': {link: {type: 'generated-index', slug: '/keep/this/route'}},
    },
  };
  const {categoriesMetadata: categories} = withGeneratedCategoryLinks(args);
  assert.equal(categories['research/ai-tools'].link.slug, '/research/ai-tools');
  assert.equal(categories['research/ai-tools'].link.description, 'AI integrations');
  assert.equal(categories['research/ai-tools/plugins'].link.slug, '/research/ai-tools/plugins');
  assert.equal(categories['research/ai-tools/plugins/deep'].link.title, 'Deep');
  assert.equal(categories['research/custom'].link, undefined);
  assert.equal(categories['research/legacy'].link.slug, '/keep/this/route');
  assert.equal(categories.research, undefined);
  assert.equal(categories['tools/excluded'], undefined);
  assert.equal(args.categoriesMetadata['research/ai-tools'].link, undefined);
});

test('new root sections receive identical repository ranking with their own overview pinned', async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'new-root-ranking-'));
  try {
    await mkdir(path.join(root, 'research'));
    const docs = ['index', 'a', 'b'].map((name) =>
      ({...doc('research', `${name}.md`), id: `research/${name}`}));
    for (const name of ['index', 'a', 'b']) {
      await writeFile(path.join(root, `research/${name}.md`), `[Source](https://github.com/owner/${name})`);
    }
    const snapshotPath = path.join(root, 'snapshot.json');
    await writeFile(snapshotPath, JSON.stringify({repositories: {'owner/b': {info: {stars: 5}}}}));
    const result = await createStarSortedSidebarGenerator({snapshotPath})({
      item: {dirName: 'research'}, docs, isCategoryIndex, version: {contentPath: root},
      defaultSidebarItemsGenerator: async () => docs.toReversed().map(({id}) => ({type: 'doc', id})),
    });
    assert.deepEqual(result.map(({id}) => id), ['research/index', 'research/b', 'research/a']);
  } finally {
    await rm(root, {recursive: true, force: true});
  }
});
